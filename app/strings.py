def get_text(key: str, lang: str = "de", **kwargs) -> str:
    """
    Returns the localised string for *key* in *lang*.
    Falls back to 'en', then returns the key itself.
    """
    entry = TEXTS.get(key)
    if not entry:
        return key
    text = entry.get(lang, entry.get("en", key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text
